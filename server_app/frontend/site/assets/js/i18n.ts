export type TKey = keyof typeof zh

/** 根据当前语言返回翻译函数；缺失键先回退中文，再返回键名。
 * Args: 无参数；读取当前应用的 locale。
 * Returns: 翻译函数；函数接收键并返回文案或键名回退。
 * Globals Used: 当前应用 Context；zh/en 文案表。Calls/Dependencies: 本文件显式导入的 React hooks、类型化动作和展示组件。
 */
export function useT(): (key: string) => string {
  const { locale } = useUi()
  return (key: string): string => {
    const table = locale === 'en' ? en : zh
    return table[key] ?? zh[key] ?? key
  }
}
